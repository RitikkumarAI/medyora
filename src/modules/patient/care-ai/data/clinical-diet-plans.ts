/**
 * Intelligent natural language classifier that maps patient queries or symptoms to the optimal clinical diet
 */
export function classifyClinicalDiet(query: string): ClinicalDietCondition {
  const lower = query.toLowerCase().trim();

  // Low BP / Hypotension keywords
  if (
    lower.includes("low bp") ||
    lower.includes("hypotension") ||
    lower.includes("bp low") ||
    lower.includes("chakkar") ||
    lower.includes("dizziness") ||
    lower.includes("faint")
  ) {
    return CLINICAL_DIET_CONDITIONS.find((d) => d.id === "hypotension-low-bp") || CLINICAL_DIET_CONDITIONS[0]!;
  }

  // High BP / Hypertension keywords
  if (
    lower.includes("high bp") ||
    lower.includes("hypertension") ||
    lower.includes("bp high") ||
    lower.includes("dash") ||
    lower.includes("salt") ||
    lower.includes("blood pressure")
  ) {
    return CLINICAL_DIET_CONDITIONS.find((d) => d.id === "hypertension-high-bp") || CLINICAL_DIET_CONDITIONS[0]!;
  }

  // Diabetes / Sugar keywords
  if (
    lower.includes("diabetes") ||
    lower.includes("sugar") ||
    lower.includes("hba1c") ||
    lower.includes("glucose") ||
    lower.includes("insulin") ||
    lower.includes("prediabetes")
  ) {
    return CLINICAL_DIET_CONDITIONS.find((d) => d.id === "diabetes-type-2") || CLINICAL_DIET_CONDITIONS[0]!;
  }

  // Fatty Liver keywords
  if (
    lower.includes("fatty liver") ||
    lower.includes("liver") ||
    lower.includes("sgpt") ||
    lower.includes("sgot") ||
    lower.includes("nafld") ||
    lower.includes("hepatic")
  ) {
    return CLINICAL_DIET_CONDITIONS.find((d) => d.id === "fatty-liver") || CLINICAL_DIET_CONDITIONS[0]!;
  }

  // Default to Fatty body / Weight loss
  return CLINICAL_DIET_CONDITIONS.find((d) => d.id === "fatty-body") || CLINICAL_DIET_CONDITIONS[0]!;
}
